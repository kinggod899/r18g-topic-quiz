def cmd_tags():
    bykind = {}
    for key, meta in tag_index().items():
        bykind.setdefault(meta["kind"], []).append((key, meta["label"]))
    names = {"axis": "轴", "hook": "钩子", "topic": "题材", "orient": "取向"}
    for kind in ("axis", "hook", "topic", "orient"):
        rows = bykind.get(kind, [])
        print("\n── %s (%d) ──" % (names[kind], len(rows)))
        for key, label in rows:
            print("  %-24s %s" % (key, label))
    print("\n── 常用别名 ──")
    for a, k in sorted(aliases().items()):
        if a != k:
            print("  %-12s → %s" % (a, k))


def cmd_check():
    errs = validate()
    total, items = stats()
    print("  桶 %d / 作品 %d" % (total, items))
    if errs:
        print("  发现 %d 处问题：" % len(errs))
        for e in errs:
            print("   - " + e)
    else:
        print("  校验通过。")


def main():
    args = sys.argv[1:]
    if args and args[0] == "tags":
        cmd_tags()
        return
    if args and args[0] == "check":
        cmd_check()
        return
    cmd_check()


if __name__ == "__main__":
    main()
