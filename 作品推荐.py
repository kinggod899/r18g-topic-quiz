# ---------------------------------------------------------------- 标签索引

def tag_index():
    idx = {}
    for k, n, d in Q.AXES:
        idx["AX:" + k] = {"label": n, "kind": "axis", "ref": k, "search": d}
    for k, n in Q.HOOKS.items():
        idx["HK:" + k] = {"label": n, "kind": "hook", "ref": k, "search": n}
    for t in Q.TOPICS:
        idx["TP:" + t["id"]] = {"label": t["name"], "kind": "topic", "ref": t["id"], "search": t.get("term", "")}
    for k, n, s in Q.ORIENTATIONS:
        idx["ORIENT:" + k] = {"label": n, "kind": "orient", "ref": k, "search": s}
    return idx


_ALIASES = None


def aliases():
    global _ALIASES
    if _ALIASES is not None:
        return _ALIASES
    a = {}
    for key, meta in tag_index().items():
        a.setdefault(meta["label"], key)
        for piece in str(meta["search"]).split("/"):
            piece = piece.strip()
            if piece:
                a.setdefault(piece, key)
    for name, key in (
        ("百合", "ORIENT:YURI"), ("GL", "ORIENT:YURI"), ("レズ", "ORIENT:YURI"), ("femslash", "ORIENT:YURI"),
        ("女性向", "ORIENT:FEMDOM"), ("乙女", "ORIENT:FEMDOM"), ("GB", "ORIENT:FEMDOM"), ("梦女", "ORIENT:FEMDOM"),
        ("男性向", "ORIENT:FM"), ("BG", "ORIENT:FM"),
    ):
        a.setdefault(name, key)
    _ALIASES = a
    return a


def normalize_tag(raw):
    """中文名 / 别名 / 规范 key → 规范 key；无法识别返回 None。"""
    s = str(raw or "").strip()
    if not s:
        return None
    idx = tag_index()
    if s in idx:
        return s
    a = aliases()
    if s in a:
        return a[s]
    for prefix in ("ORIENT:", "TP:", "HK:", "AX:"):
        if prefix + s in idx:
            return prefix + s
    return None


