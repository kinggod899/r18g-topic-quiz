def validate():
    errs = []
    idx = tag_index()
    ids = {}
    for tag, bucket in RECO_BUCKETS.items():
        if tag not in idx:
            errs.append("未知标签桶: " + tag)
        for m, items in bucket.items():
            if m not in MEDIA:
                errs.append("未知媒体: %s / %s" % (tag, m))
            for w in items:
                label = "%s/%s/%s" % (tag, m, w.get("id") or w.get("title") or "?")
                for f in REQUIRED:
                    if not w.get(f):
                        errs.append("缺字段 %s: %s" % (f, label))
                if w.get("media") != m:
                    errs.append("媒体不符 %s: media=%s 桶=%s" % (label, w.get("media"), m))
                for field, valid in (("language", VALID_LANG), ("length", VALID_LENGTH),
                                     ("orientation", VALID_ORIENT)):
                    val = w.get(field, "" if field != "orientation" else "FM")
                    if val and val not in valid:
                        errs.append("%s 非法 %s: %s" % (field, label, val))
                wid = w.get("id")
                if wid:
                    key = (tag, m, wid)
                    if key in ids:
                        errs.append("桶内重复 id %s: %s" % (wid, key))
                    else:
                        ids[key] = label
    return errs


