def _score_work(w, tag, main, soft, hooks, topics, lang_mode, length):
    s = 0
    why = []
    if tag in topics:
        s += 5
        why.append("推荐题材")
    if tag.startswith("AX:"):
        k = tag[3:]
        if k in main:
            s += 4
            why.append("主轴")
        elif k in soft:
            s += 2
            why.append("副轴")
    if tag.startswith("HK:") and tag[3:] in hooks:
        s += 3
        why.append("命中钩子")
    if lang_mode == 0 and w.get("language", "zh") == "zh":
        s += 1
    if length and w.get("length") == length:
        s += 1
    return s, why


def for_profile(profile):
    """按坐标 + 阅读条件返回三类作品清单（命令行版）。"""
    media = set(profile.get("media") or MEDIA)
    main = set(profile.get("main") or [])
    soft = set(profile.get("soft") or [])
    hooks = set(profile.get("hooks") or [])
    topics = set("TP:" + t for t in (profile.get("topics") or []))
    taboos = set(profile.get("taboos") or [])
    lang_mode = profile.get("language", 2)
    length = profile.get("length") or ""

    taboo_hooks = set()
    taboo_map = dict((t[0], t[2]) for t in Q.TABOOS)
    for tid in taboos:
        for h in taboo_map.get(tid, []):
            taboo_hooks.add(h)

    out = {m: [] for m in MEDIA}
    seen = {}
    for tag, bucket in RECO_BUCKETS.items():
        for m in MEDIA:
            for w in bucket.get(m, []):
                if m not in media:
                    continue
                if "ORIENT_FEMDOM" in taboos and w.get("orientation", "FM") == "FEMDOM":
                    continue
                if taboo_hooks & set(w.get("avoid") or []):
                    continue
                if lang_mode == 0 and w.get("language", "zh") == "ja":
                    continue
                s, why = _score_work(w, tag, main, soft, hooks, topics, lang_mode, length)
                wid = w.get("id") or w.get("title")
                rec = {"work": w, "score": s, "why": why, "tags": [tag]}
                if wid in seen:
                    prev = seen[wid]
                    prev["score"] += s
                    prev["why"] += why
                    prev["tags"].append(tag)
                else:
                    seen[wid] = rec
                    out[m].append(rec)
    for m in MEDIA:
        out[m].sort(key=lambda r: (-r["score"], r["work"].get("year") or 0, r["work"].get("title", "")))
    return out


